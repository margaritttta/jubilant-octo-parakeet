import pandas as pd, sqlite3
conn = sqlite3.connect('shop.db')
df = pd.read_sql("""
    SELECT p.product_name, p.category, pr.price
    FROM prices pr
    JOIN products p ON pr.product_id = p.product_id
""", conn)
conn.close()

q1 = df['price'].quantile(0.25)
q2 = df['price'].quantile(0.50)
q3 = df['price'].quantile(0.75)
iqr = q3 - q1

above_q3 = df[df['price'] > q3][['product_name', 'category', 'price']].sort_values('price', ascending=False)


quartiles_table = pd.DataFrame({
    'Показатель': ['Q1 (25-й процентиль)', 'Q2 (медиана, 50%)', 'Q3 (75-й процентиль)', 'IQR (межквартильный размах)'],
    'Значение': [f"{q1:.2f} руб.", f"{q2:.2f} руб.", f"{q3:.2f} руб.", f"{iqr:.2f} руб."]
})

print(quartiles_table.to_string(index=False))

print("\nТовары с ценой выше Q3".format(q3))
