import pandas as pd
import sqlite3
conn = sqlite3.connect('shop.db')
df = pd.read_sql("""
    SELECT p.category, pr.price
    FROM prices pr
    JOIN products p ON pr.product_id = p.product_id
""", conn)
conn.close()


by_category = df.groupby('category')['price'].agg(
    count='count',
    avg_price='mean',
    median_price='median',
    std_price='std'
).round(2).sort_values('avg_price', ascending=False).reset_index()

by_category.columns = [
    'Категория',
    'Кол-во записей',
    'Средняя цена (руб.)',
    'Медиана (руб.)',
    'Ст. отклонение (руб.)'
]

print(by_category.to_string(index=False))

import pandas as pd
import sqlite3
conn = sqlite3.connect('shop.db')
df = pd.read_sql("""
    SELECT p.product_name, pr.price
    FROM prices pr
    JOIN products p ON pr.product_id = p.product_id
""", conn)
conn.close()

all_products = df.groupby('product_name')['price'].agg(
    min_p='min',
    max_p='max'
).reset_index()

all_products['Разброс'] = (all_products['max_p'] - all_products['min_p']).round(2)

top5 = all_products.sort_values('Разброс', ascending=False).head(5)

top5.columns = [
    'Товар',
    'Мин. цена (руб.)',
    'Макс. цена (руб.)',
    'Разброс (руб.)'
]

print(top5.to_string(index=False))